export function getPlanetPlacementReading(planet: PlanetPosition, hasExactBirthTime: boolean) {
  const reading = hasExactBirthTime ? readings[planet.key]?.[planet.house - 1] : undefined;
  return {
    title: `${planet.name} in ${planet.sign}${reading ? ` (House ${planet.house})` : ''}`,
    reading,
  };
}
