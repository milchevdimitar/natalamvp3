import { BirthPickerFields } from '../components/BirthPickerFields';
import type { BirthDate } from '../components/BirthWheelPicker';
import React, { useEffect, useRef, useState } from 'react';
import {
  ActivityIndicator, Animated, KeyboardAvoidingView, Modal, Platform, Pressable,
  ScrollView, StyleSheet, Text, TextInput, View,
} from 'react-native';
import { Check, Eye, EyeOff } from 'lucide-react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { BackButton } from '../components/BackButton';
import { BackendStatus } from '../components/BackendStatus';
import { CitySearchPicker } from '../components/CitySearchPicker';
import { useApp } from '../context/AppContext';
import { accountMethods, authenticate, sendEmailCode } from '../services/account';
import type { CityLocation } from '../services/locationService';
import { cosmic } from '../theme/cosmic';
import { CosmicBackground, useReducedMotion } from './Home/CosmicBackground';

const TERMS_VERSION = '2026-11-24';
const genders = [{ value: 'male', label: 'Male' }, { value: 'female', label: 'Female' }, { value: 'other', label: 'Other' }] as const;

const terms = [
  ['Using Natala', 'Natala offers tools for self-reflection and ways to connect with others. Astrology, tarot and other readings are interpretive. Some readings are generated by AI and can contain mistakes. Use your own judgment when making decisions, and seek qualified advice for medical, legal or financial matters.'],
  ['Your account', 'Use an email you can access and keep your password private. Add birth details you are entitled to share. You can delete your account from Settings.'],
  ['Sharing and community', 'Share only content you have permission to share. Treat other people with respect. Harassment, impersonation, spam and unlawful content are prohibited. Natala may restrict accounts or remove content that violates these rules.'],
  ['Plans and subscriptions', 'If you choose a paid plan, review its price, billing period and renewal terms before confirming. Manage or cancel the plan through the billing provider used to purchase it. Your applicable consumer rights still apply.'],
];

export default function Login() {
  const { setUser, setPage, setAccount } = useApp();
  const reduced = useReducedMotion();
  const offset = useRef(new Animated.Value(0)).current;
  const [register, setRegister] = useState(false);
  const [focusedField, setFocusedField] = useState<string | null>(null);
  const [name, setName] = useState('');
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [showPassword, setShowPassword] = useState(false);
  const [birth, setBirth] = useState<BirthDate | null>(null);
  const [birthTime, setBirthTime] = useState('');
  const [city, setCity] = useState<CityLocation | null>(null);
  const [gender, setGender] = useState<(typeof genders)[number]['value'] | null>(null);
  const [accepted, setAccepted] = useState(false);
  const [termsOpen, setTermsOpen] = useState(false);
  const [needsCode, setNeedsCode] = useState(false);
  const [sentTo, setSentTo] = useState('');
  const [code, setCode] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  useEffect(() => { void accountMethods().then((methods) => setNeedsCode(methods.emailVerification)).catch(() => {}); }, []);

  const normalizedEmail = email.trim().toLowerCase();
  const codeSent = sentTo === normalizedEmail && sentTo !== '';
  const missingPasswordCharacters = 8 - password.length;
  const shortPassword = register && password.length > 0 && missingPasswordCharacters > 0;
  const canSubmit = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(normalizedEmail) && password.length >= 8 &&
    (!register || Boolean(name.trim() && birth && city && gender && accepted));

  const submit = async () => {
    if (busy || !canSubmit) return;
    setBusy(true);
    setError('');
    try {
      const methods = register ? await accountMethods() : null;
      if (methods && methods.termsVersion !== TERMS_VERSION) {
        throw new Error('Registration is unavailable on this server. Please try again after it is updated.');
      }
      if (methods?.emailVerification && !codeSent) {
        setNeedsCode(true);
        await sendEmailCode(normalizedEmail);
        setSentTo(normalizedEmail);
        setCode('');
        return;
      }
      const result = await authenticate('/email', {
        email: normalizedEmail, password, register,
        ...(register && { name: name.trim(), gender, birth: { ...birth, city, time: birthTime }, termsVersion: TERMS_VERSION, code }),
      });
      setAccount(result);
      setUser(result.user);
      setPage('home');
    } catch (failure) {
      const message = failure instanceof Error ? failure.message : 'Please try again.';
      if (register && message.includes('verification code')) setNeedsCode(true);
      setError(message);
    } finally {
      setBusy(false);
    }
  };

  function field(label: string, value: string, onChangeText: (value: string) => void, props: React.ComponentProps<typeof TextInput> = {}) {
    return <View style={styles.field}>
      <Text style={styles.label}>{label}</Text>
      <TextInput {...props} accessibilityLabel={label} style={styles.input} value={value} onChangeText={onChangeText}
        editable={!busy} placeholder={focusedField === label ? '' : label + '...'} placeholderTextColor={cosmic.line}
        onFocus={() => setFocusedField(label)} onBlur={() => setFocusedField(null)} />
    </View>;
  }

  return <View style={styles.screen}>
    <CosmicBackground offset={offset} reduced={reduced} darkBottom />
    <SafeAreaView style={styles.flex}>
      <KeyboardAvoidingView style={styles.flex} behavior={Platform.OS === 'ios' ? 'padding' : undefined}>
        <ScrollView keyboardShouldPersistTaps="handled" contentContainerStyle={styles.scroll}>
          <View style={styles.content}>
            <Text style={styles.logo}>Natala</Text>
            <BackendStatus />
            <View style={styles.form}>
              {register && field('Name', name, setName, { autoComplete: 'name', autoCapitalize: 'words', maxLength: 80 })}
              {field('Email', email, (value) => { setEmail(value); setSentTo(''); setCode(''); }, {
                autoComplete: 'email', inputMode: 'email', autoCapitalize: 'none', autoCorrect: false, maxLength: 254,
              })}
              <View style={styles.field}>
                <Text style={styles.label}>Password</Text>
                <View style={[styles.passwordRow, shortPassword && styles.shortPassword]}>
                  <TextInput accessibilityLabel="Password" style={styles.passwordInput} value={password} onChangeText={setPassword}
                    autoComplete={register ? 'new-password' : 'current-password'} autoCapitalize="none" autoCorrect={false}
                    secureTextEntry={!showPassword} maxLength={128} editable={!busy}
                    placeholder={focusedField === 'Password' ? '' : 'Password...'} placeholderTextColor={shortPassword ? '#c89b69' : cosmic.line}
                    onFocus={() => setFocusedField('Password')} onBlur={() => setFocusedField(null)}
                    onSubmitEditing={register ? undefined : () => { void submit(); }} />
                  <Pressable accessibilityRole="button" accessibilityLabel={showPassword ? 'Hide password' : 'Show password'}
                    onPress={() => setShowPassword(!showPassword)} style={styles.iconButton}>
                    {showPassword ? <EyeOff size={19} color={cosmic.muted} /> : <Eye size={19} color={cosmic.muted} />}
                  </Pressable>
                </View>
                {shortPassword && (
                  <Text accessibilityLiveRegion="polite" style={styles.passwordHint}>
                    Add {missingPasswordCharacters} more {missingPasswordCharacters === 1 ? 'character' : 'characters'}.
                  </Text>
                )}
              </View>
              {register && <>
                <BirthPickerFields date={birth} time={birthTime} onDateChange={setBirth}
                  onTimeChange={setBirthTime} colors={cosmic} disabled={busy} />
                <View style={styles.field}>
                  <Text style={styles.label}>Place of birth</Text>
                  <CitySearchPicker selectedCity={city} onSelectCity={setCity} colors={cosmic} cosmicTheme="dark" />
                </View>
                <View style={styles.field}>
                  <Text style={styles.label}>Gender</Text>
                  <View style={styles.choices}>{genders.map(({ value, label }) => (
                    <Pressable key={value} accessibilityRole="radio" accessibilityState={{ checked: gender === value }}
                      disabled={busy} onPress={() => setGender(value)} style={[styles.choice, gender === value && styles.selected]}>
                      <Text style={styles.label}>{label}</Text>
                    </Pressable>
                  ))}</View>
                </View>
                <View style={styles.termsRow}>
                  <Pressable accessibilityRole="checkbox" accessibilityLabel="I agree to the Terms of Use"
                    accessibilityState={{ checked: accepted }} disabled={busy} onPress={() => setAccepted(!accepted)} style={styles.checkButton}>
                    <View style={[styles.checkbox, accepted && styles.selected]}>{accepted && <Check size={15} color={cosmic.muted} />}</View>
                    <Text style={styles.label}>I agree to the</Text>
                  </Pressable>
                  <Pressable accessibilityRole="button" onPress={() => setTermsOpen(true)} style={styles.textButton}>
                    <Text style={styles.link}>Terms of Use</Text>
                  </Pressable>
                </View>
                {needsCode && codeSent && field('Email verification code', code, setCode, { inputMode: 'numeric', autoComplete: 'one-time-code', maxLength: 8 })}
              </>}
              {!!error && <Text accessibilityRole="alert" style={styles.error}>{error}</Text>}
              <Pressable accessibilityRole="button" disabled={!canSubmit || busy || (register && needsCode && codeSent && !/^\d{8}$/.test(code))}
                style={({ pressed }) => [styles.primary, (!canSubmit || busy || (register && needsCode && codeSent && code.length !== 8)) && styles.dimmed, pressed && styles.dimmed]}
                onPress={() => { void submit(); }}>
                {busy ? <ActivityIndicator color={cosmic.bg} /> : <Text style={styles.primaryText}>{register ? needsCode && !codeSent ? 'Send verification code' : 'Create account' : 'Sign in'}</Text>}
              </Pressable>
            </View>
            <Pressable accessibilityRole="button" disabled={busy} style={[styles.textButton, styles.mode]}
              onPress={() => { setRegister(!register); setError(''); setShowPassword(false); }}>
              <Text style={styles.link}>{register ? 'Already have an account? Sign in' : 'New to Natala? Create an account'}</Text>
            </Pressable>
          </View>
        </ScrollView>
      </KeyboardAvoidingView>
    </SafeAreaView>
    {termsOpen && <Modal visible animationType={reduced ? 'none' : 'slide'} onRequestClose={() => setTermsOpen(false)}>
      <View style={styles.screen}>
        <CosmicBackground offset={offset} reduced={reduced} darkBottom />
        <SafeAreaView style={styles.flex}>
          <View style={styles.modalHeader}><BackButton onPress={() => setTermsOpen(false)} onDark />
            <Text accessibilityRole="header" style={styles.modalTitle}>Terms of Use</Text>
          </View>
          <ScrollView contentContainerStyle={styles.options}>
            {terms.map(([heading, text]) => <View key={heading} style={styles.termSection}>
              <Text accessibilityRole="header" style={styles.label}>{heading}</Text>
              <Text style={styles.termsCopy}>{text}</Text>
            </View>)}
          </ScrollView>
        </SafeAreaView>
      </View>
    </Modal>}
  </View>;
}

const styles = StyleSheet.create({
  screen: { flex: 1, backgroundColor: cosmic.bg },
  flex: { flex: 1 },
  scroll: { flexGrow: 1, padding: 18, justifyContent: 'center' },
  content: { width: '100%', maxWidth: 430, alignSelf: 'center', paddingVertical: 16, gap: 10 },
  logo: { fontFamily: 'DancingScript_700Bold', fontSize: 52, lineHeight: 63, color: cosmic.text, textAlign: 'center' },
  form: { gap: 13, padding: 16, borderWidth: 1, borderColor: "transparent" },
  field: { gap: 6 },
  label: { color: cosmic.text, fontSize: 14, fontWeight: '600' },
  input: { minHeight: 48, paddingHorizontal: 12, borderRadius: 12, borderWidth: 1, borderColor: cosmic.line, backgroundColor: 'rgba(255,255,255,0.06)', color: cosmic.text, fontSize: 16 },
  passwordRow: { minHeight: 48, flexDirection: 'row', alignItems: 'center', borderRadius: 12, borderWidth: 1, borderColor: cosmic.line, backgroundColor: 'rgba(255,255,255,0.06)' },
  passwordInput: { flex: 1, minHeight: 46, paddingHorizontal: 12, color: cosmic.text, fontSize: 16 },
  iconButton: { width: 44, minHeight: 44, alignItems: 'center', justifyContent: 'center' },
  shortPassword: { borderColor: '#c89b69' },
  passwordHint: { color: '#e9c394', fontSize: 12 },
  choices: { flexDirection: 'row', gap: 7 },
  choice: { flex: 1, minHeight: 44, alignItems: 'center', justifyContent: 'center', borderWidth: 1, borderColor: cosmic.line, borderRadius: 12 },
  selected: { borderColor: cosmic.purple, backgroundColor: 'rgba(180,156,255,0.26)' },
  termsRow: { flexDirection: 'row', alignItems: 'center', flexWrap: 'wrap', gap: 4 },
  checkButton: { minHeight: 44, flexDirection: 'row', alignItems: 'center', gap: 8 },
  checkbox: { width: 22, height: 22, borderWidth: 1, borderColor: cosmic.muted, borderRadius: 5, alignItems: 'center', justifyContent: 'center' },
  textButton: { minHeight: 44, justifyContent: 'center' },
  mode: { alignSelf: 'center' },
  link: { color: '#d5c8ff', fontSize: 14, fontWeight: '700' },
  error: { color: '#ffc2c7', lineHeight: 20 },
  primary: { alignItems: 'center', justifyContent: 'center', minHeight: 48, borderRadius: 13, backgroundColor: '#d5c8ff' },
  primaryText: { color: cosmic.bg, fontSize: 16, fontWeight: '800' },
  dimmed: { opacity: 0.55 },
  modalHeader: { flexDirection: 'row', alignItems: 'center', gap: 6, paddingHorizontal: 18, paddingTop: 8 },
  modalTitle: { color: cosmic.text, fontSize: 20, fontWeight: '800' },
  options: { width: '100%', maxWidth: 500, alignSelf: 'center', padding: 18, gap: 8 },
  termSection: { padding: 16, gap: 7, borderRadius: 14, backgroundColor: cosmic.surface },
  termsCopy: { color: cosmic.muted, fontSize: 15, lineHeight: 22 },
});
